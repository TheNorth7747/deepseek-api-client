/** 取最近的地级市中心；超过 2.5 度视为不可信，返回 undefined */
export const nearestCity = (lat: number, lon: number) => {
  let best: { code: string; distance: number } | undefined
  for (const city of cityCenters) {
    const dLat = city.lat - lat
    const dLon = (city.lon - lon) * Math.cos((lat * Math.PI) / 180)
    const distance = Math.sqrt(dLat * dLat + dLon * dLon)
    if (!best || distance < best.distance) {
      best = { code: city.code, distance }
    }
  }
  return best && best.distance <= 2.5 ? best.code : undefined
}
